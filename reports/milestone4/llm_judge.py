"""
LLM-as-judge comparison between tuned and baseline Gemini responses.

Usage:
    python reports/milestone4/llm_judge.py \
        --input data/evaluation_compare.json \
        --output reports/milestone4/llm_judge_results.json \
        --project-id <PROJECT> --judge-model gemini-1.5-pro

The script expects the input JSON generated by evaluate_tuned_model.py.
Each entry should contain: question, ground_truth, tuned_prediction, base_prediction.
"""

import argparse
import json
import logging
import os
import re
import time
from pathlib import Path
from typing import Dict, List, Tuple

from google.cloud import aiplatform
from vertexai.generative_models import GenerativeModel

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)

PROMPT_TEMPLATE = """You are an impartial judge evaluating two model answers to the same financial question.
Consider correctness, completeness, and clarity. Use the ground truth as reference when possible.

Respond in JSON with keys "winner" ("tuned", "base", or "tie") and "rationale".
Here is the evaluation sample:

Question: {question}
Ground truth: {ground_truth}

Answer A (tuned model):
{tuned_answer}

Answer B (baseline model):
{base_answer}

Return:
{{
  "winner": "...",
  "rationale": "..."
}}
"""


def parse_judge_response(text: str) -> Tuple[str, str]:
    """Extract winner/rationale JSON fragment from model output."""
    text = text.strip()
    json_match = re.search(r"\{.*\}", text, re.DOTALL)
    if json_match:
        fragment = json_match.group(0)
        try:
            payload = json.loads(fragment)
            return payload.get("winner", "unknown"), payload.get("rationale", text)
        except json.JSONDecodeError:
            logger.debug("Failed to parse JSON fragment: %s", fragment)
    return "unknown", text


def load_examples(path: str) -> List[Dict]:
    data_path = Path(path)
    if not data_path.exists():
        raise FileNotFoundError(f"Evaluation comparison file not found: {path}")
    with data_path.open() as f:
        payload = json.load(f)
    return payload.get("examples", [])


def run_judging(
    examples: List[Dict],
    judge_model,  # Can be GenerativeModel or langchain VertexAI
    limit: int,
    sleep: float,
    is_langchain: bool = False,
) -> Dict:
    results = []
    stats = {"tuned": 0, "base": 0, "tie": 0, "unknown": 0}

    for idx, example in enumerate(examples[:limit], start=1):
        question = example.get("question", "")
        ground_truth = example.get("ground_truth", "")
        tuned_answer = example.get("tuned_prediction", "")
        base_answer = example.get("base_prediction", "")
        prompt = PROMPT_TEMPLATE.format(
            question=question,
            ground_truth=ground_truth,
            tuned_answer=tuned_answer,
            base_answer=base_answer or "(baseline response missing)",
        )

        try:
            if is_langchain:
                response_text = judge_model.invoke(prompt, temperature=0.0, max_tokens=512, top_p=1.0)
            else:
                response = judge_model.generate_content(
                    prompt,
                    generation_config={
                        "temperature": 0.0,
                        "top_p": 1.0,
                        "max_output_tokens": 512,
                    },
                )
                response_text = response.text
            winner, rationale = parse_judge_response(response_text)
        except Exception as exc:  # pragma: no cover - requires Vertex AI runtime
            logger.warning("Judge request failed for example %s: %s", idx, exc)
            winner, rationale = "unknown", str(exc)

        stats[winner] = stats.get(winner, 0) + 1
        results.append(
            {
                "question": question,
                "winner": winner,
                "rationale": rationale,
                "ground_truth": ground_truth,
                "tuned_prediction": tuned_answer,
                "base_prediction": base_answer,
            }
        )

        if idx % 10 == 0:
            logger.info("Judged %s examples", idx)
        time.sleep(sleep)

    return {"judgements": results, "summary": stats}


def main():
    parser = argparse.ArgumentParser(description="Run LLM-as-judge on tuned vs base predictions")
    parser.add_argument("--input", type=str, default="data/evaluation_compare.json", help="Path to comparison JSON file")
    parser.add_argument(
        "--output",
        type=str,
        default="reports/milestone4/llm_judge_results.json",
        help="Where to store judge decisions",
    )
    parser.add_argument("--project-id", type=str, help="GCP project ID (defaults to env GCP_PROJECT_ID)")
    parser.add_argument("--location", type=str, default="us-central1", help="Vertex AI region")
    parser.add_argument("--judge-model", type=str, default="gemini-2.5-pro", help="Vertex model id for judging")
    parser.add_argument("--limit", type=int, default=50, help="Number of samples to judge")
    parser.add_argument("--sleep", type=float, default=0.5, help="Delay between judge calls (seconds)")

    args = parser.parse_args()

    project_id = args.project_id or os.getenv("GCP_PROJECT_ID")
    if not project_id:
        raise ValueError("Provide --project-id or set GCP_PROJECT_ID")

    examples = load_examples(args.input)
    if not examples:
        raise ValueError("No examples found in comparison file. Run evaluate_tuned_model.py first.")

    # Use langchain's VertexAI for judge (avoids publisher model 404 errors)
    from langchain_google_vertexai import VertexAI

    aiplatform.init(project=project_id, location=args.location)
    judge = VertexAI(model_name=args.judge_model, project=project_id, location=args.location)
    logger.info("Loaded judge model via langchain: %s", args.judge_model)

    payload = run_judging(examples, judge, args.limit, args.sleep, is_langchain=True)

    output_path = Path(args.output)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w") as f:
        json.dump(payload, f, indent=2)

    logger.info("Saved judge summary to %s", output_path)
    logger.info("Summary: %s", payload["summary"])


if __name__ == "__main__":
    main()
